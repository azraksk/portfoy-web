const params = new URLSearchParams(window.location.search);
const id = Number(params.get("id"));

const cert = data.find(item => item.id === id);

if (cert) {
  // Görsel ve temel bilgiler
  document.getElementById("certImage").src = cert.img;
  document.getElementById("certTitle").innerText = cert.title;
  document.getElementById("certDate").innerText = cert.date;
  document.getElementById("certOrg").innerText = cert.org;
  document.getElementById("certDesc").innerText = cert.desc;

  // 🧠 Kazanımlar listesi
  const skillsList = document.getElementById("certSkills");
  skillsList.innerHTML = ""; // önce temizle
  cert.skills.forEach(skill => {
    const li = document.createElement("li");
    li.innerText = skill;
    skillsList.appendChild(li);
  });

  // 🏷️ Etiketler
  const tagsDiv = document.getElementById("certTags");
  tagsDiv.innerHTML = ""; // önce temizle
  cert.tags.forEach(tag => {
    const span = document.createElement("span");
    span.classList.add("cert-tag"); // CSS için
    span.innerText = tag;
    tagsDiv.appendChild(span);
  });
}

